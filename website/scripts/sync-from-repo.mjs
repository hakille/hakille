  const fontsSrcDir = join(REPO_ROOT, 'mobile/ios/Hakille/Fonts');
  const fontsDestDir = join(WEBSITE_ROOT, 'public/fonts');
  ensureDir(fontsDestDir);

  const interSrc = join(fontsSrcDir, 'InterVariable.ttf');
  const oflSrc = join(fontsSrcDir, 'OFL.txt');
  const provSrc = join(fontsSrcDir, 'PROVENANCE.txt');

  const interHash = sha256File(interSrc);
  const oflHash = sha256File(oflSrc);

  if (interHash !== EXPECTED_INTER_SHA256) {
    throw new Error(`InterVariable.ttf SHA-256 mismatch: expected ${EXPECTED_INTER_SHA256}, got ${interHash}`);
  }
  if (oflHash !== EXPECTED_OFL_SHA256) {
    throw new Error(`OFL.txt SHA-256 mismatch: expected ${EXPECTED_OFL_SHA256}, got ${oflHash}`);
  }

  copyFileSync(interSrc, join(fontsDestDir, 'InterVariable.ttf'));
  copyFileSync(oflSrc, join(fontsDestDir, 'OFL.txt'));
  copyFileSync(provSrc, join(fontsDestDir, 'PROVENANCE.txt'));

